-- NetBench database schema. Safe to run repeatedly (IF NOT EXISTS).
--
-- Rule of thumb used here: anything we filter, group or join on gets a real
-- column; flexible, test-specific detail goes into JSONB.

CREATE TABLE IF NOT EXISTS runs (
    run_id         UUID PRIMARY KEY,           -- generated by the client, so retries can't duplicate a run
    started_at     TIMESTAMPTZ NOT NULL,       -- when the client started (stored in UTC)
    received_at    TIMESTAMPTZ NOT NULL DEFAULT now(),  -- when the backend got it
    network        TEXT NOT NULL,              -- "home-wifi", "uni-net", ...
    server         TEXT NOT NULL,              -- measurement server host:port
    client         JSONB NOT NULL,             -- OS, machine, Python version
    schema_version INT NOT NULL
);

CREATE TABLE IF NOT EXISTS test_results (
    run_id        UUID NOT NULL REFERENCES runs (run_id) ON DELETE CASCADE,
    test          TEXT NOT NULL,               -- "cyclic_udp", "reqresp_tcp", "bulk_tcp"
    passed        BOOLEAN NOT NULL,
    error         TEXT,                        -- set when the test could not run at all
    params        JSONB NOT NULL,
    thresholds    JSONB,
    metrics       JSONB,
    failed_checks JSONB,
    samples_ms    JSONB,                       -- raw RTTs, null = lost packet
    PRIMARY KEY (run_id, test)                 -- one result per test per run
);

-- The most common question will be "all runs on network X, over time".
CREATE INDEX IF NOT EXISTS runs_network_started ON runs (network, started_at);
